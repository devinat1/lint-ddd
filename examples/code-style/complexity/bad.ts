export const rank = (score: number): string => {
  if (score === 0) {
    return "a";
  }
  if (score === 1) {
    return "b";
  }
  if (score === 2) {
    return "c";
  }
  if (score === 3) {
    return "d";
  }
  if (score === 4) {
    return "e";
  }
  if (score === 5) {
    return "f";
  }
  if (score === 6) {
    return "g";
  }
  if (score === 7) {
    return "h";
  }
  if (score === 8) {
    return "i";
  }
  if (score === 9) {
    return "j";
  }
  if (score === 10) {
    return "k";
  }
  if (score === 11) {
    return "l";
  }
  if (score === 12) {
    return "m";
  }
  if (score === 13) {
    return "n";
  }
  if (score === 14) {
    return "o";
  }
  if (score === 15) {
    return "p";
  }
  return "q";
}
